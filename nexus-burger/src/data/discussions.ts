export const discussions: Discussion[] = Object.entries(groups).flatMap(([topic, entries]) =>
  entries.map((entry, index) => ({
    id: `${topic}-${index}`,
    topic: topic as DiscussionTopic,
    text: typeof entry === 'string' ? entry : entry[0],
    code: typeof entry === 'string' ? undefined : entry[1],
  }))
)

export function createDiscussionPicker() {
  const bags = new Map<DiscussionTopic, Discussion[]>()
  return (topic: DiscussionTopic) => {
    let bag = bags.get(topic)
    if (!bag?.length) {
      bag = discussions.filter((entry) => entry.topic === topic)
      for (let i = bag.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1))
        ;[bag[i], bag[j]] = [bag[j], bag[i]]
      }
      bags.set(topic, bag)
    }
    return bag.pop()!
  }
}
